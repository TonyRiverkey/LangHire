import { expect, it, vi } from "vitest";
import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import MainResumeImprover from "./MainResumeImprover";
import { activateMainResume, draftMainResume } from "../lib/applicationDocuments";
vi.mock("../lib/applicationDocuments", () => ({ activateMainResume: vi.fn(), draftMainResume: vi.fn() }));
vi.mock("./ApplicationDocuments", () => ({ PdfFiles: () => <div>PDF previews</div> }));
it("requires actual experience and draft review before replacing the main resume", async () => {
  vi.mocked(draftMainResume).mockResolvedValue({ id: "draft1", original: "Original", revised: "Improved", source_asset: "source", draft_asset: "draft" });
  vi.mocked(activateMainResume).mockResolvedValue({ success: true, previous_path: "original.pdf" });
  const user = userEvent.setup();
  render(<MainResumeImprover jobUrl="https://example.com/a" skills={[{ skill: "HRIS", evidence: "HRIS required", reason: "Reporting" }]} />);
  await user.click(screen.getByText("Improve main resume from these skills"));
  const generate = screen.getByRole("button", { name: "Generate main resume improvement draft" });
  expect(generate).toBeDisabled();
  await user.click(screen.getByLabelText("I have experience with HRIS"));
  expect(generate).toBeDisabled();
  await user.type(screen.getByLabelText("Your actual experience with HRIS"), "I maintained employee data in SuccessFactors.");
  await user.click(generate);
  expect(draftMainResume).toHaveBeenCalledWith("https://example.com/a", [{ skill: "HRIS", experience: "I maintained employee data in SuccessFactors." }]);
  expect(await screen.findByLabelText("Proposed main resume")).toHaveValue("Improved");
  const useDraft = screen.getByRole("button", { name: "Use this as my main resume" });
  expect(useDraft).toBeDisabled();
  expect(activateMainResume).not.toHaveBeenCalled();
  await user.click(screen.getByLabelText("I reviewed the draft PDF and confirmed every statement is accurate."));
  await user.click(useDraft);
  await waitFor(() => expect(activateMainResume).toHaveBeenCalledWith("draft1"));
  expect(await screen.findByText(/previous file is preserved/)).toBeInTheDocument();
});
